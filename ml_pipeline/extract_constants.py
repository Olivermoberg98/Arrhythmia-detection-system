#!/usr/bin/env python3
"""
STEPS 2 + 3 — xxd C-array generation + scaler / threshold extraction.

Usage
-----
    python extract_constants.py \
        --tflite      src/ml/arrhythmia_model.tflite \
        --meta        data/processed/metadata.pkl \
        --ecg_scaler  data/processed/ecg_scaler.pkl \
        --rr_scaler   data/processed/rr_scaler.pkl \
        --results     models/trained/results_XXXXXX.pkl \
        --out_data    src/ml/model_data.h \
        --out_cfg     src/ml/model_config.h

Outputs
-------
  model_data.h    — g_model[] C array (replaces stub in model.h)
  model_config.h  — all normalisation constants + thresholds as constexpr
"""

import argparse
import pickle
import subprocess
import sys
from pathlib import Path
from textwrap import dedent

import numpy as np


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #

def load_pkl(path: str):
    with open(path, "rb") as f:
        return pickle.load(f)


def normalise_class_names(raw) -> list[str]:
    """
    class_names may be stored as:
      - a list  : ["Normal", "SVEB", "VEB"]
      - a dict  : {0: "Normal", 1: "SVEB", 2: "VEB"}
    Always returns a sorted list.
    """
    if isinstance(raw, dict):
        return [raw[k] for k in sorted(raw.keys())]
    return list(raw)


def tflite_to_c_array(tflite_path: Path) -> tuple[str, int]:
    """
    Binary .tflite → C hex literal string.
    Uses xxd when available, pure Python fallback otherwise.
    Returns (c_body: str, byte_count: int).
    """
    data = tflite_path.read_bytes()
    n    = len(data)

    try:
        result = subprocess.run(
            ["xxd", "-i", str(tflite_path)],
            capture_output=True, text=True, check=True
        )
        # Strip the variable declaration lines; keep only the hex body.
        lines = result.stdout.splitlines()
        body_lines = [
            l for l in lines
            if l.strip()
            and not l.strip().startswith("unsigned")
            and l.strip() not in ("{", "}", "};")
        ]
        return "\n".join(body_lines), n

    except (FileNotFoundError, subprocess.CalledProcessError):
        # Pure Python fallback (works on Windows without xxd installed)
        tokens = [f"0x{b:02x}" for b in data]
        lines, line = [], "  "
        for tok in tokens:
            if len(line) + len(tok) + 2 > 80:
                lines.append(line)  # Keep the trailing comma
                line = "  "
            line += tok + ", "
        if line.strip():
            lines.append(line.rstrip(", "))  # Only remove comma from last line
        return "\n".join(lines), n


def fmt_scalar(val: float, name: str, comment: str = "") -> str:
    cmt = f"  // {comment}" if comment else ""
    return f"    constexpr float {name} = {val:.8f}f;{cmt}"


def fmt_array(arr: np.ndarray, name: str, comment: str = "") -> str:
    vals = ", ".join(f"{v:.8f}f" for v in arr)
    cmt  = f"  // {comment}" if comment else ""
    return f"    constexpr float {name}[{len(arr)}] = {{{vals}}};{cmt}"


# --------------------------------------------------------------------------- #
# Header writers
# --------------------------------------------------------------------------- #

def write_model_data_h(c_body: str, model_len: int, out: Path) -> None:
    text = dedent(f"""\
    #pragma once
    /**
     * @file  model_data.h
     * @brief TFLite flat-buffer as a C array.
     *
     * Auto-generated by extract_constants.py - DO NOT EDIT.
     */
    #include <stdint.h>

    // 8-byte alignment required by TFLite Micro's FlatBuffer parser.
    alignas(8) const unsigned char g_model[] = {{
    {c_body}
    }};

    const unsigned int g_model_len = {model_len}U;
    """)
    out.write_text(text, encoding="utf-8")
    print(f"  model_data.h  -> {out}  ({model_len:,} bytes)")


def write_model_config_h(
    meta:       dict,
    ecg_mean:   np.ndarray,   # shape (1,) or (beat_len,)
    ecg_std:    np.ndarray,
    rr_mean:    np.ndarray,   # shape (n_rr,)
    rr_std:     np.ndarray,
    thresholds: list[float],
    out:        Path,
) -> None:
    beat_len    = int(meta.get("beat_length",   250))
    n_rr        = int(meta.get("n_rr_features", 3))
    class_names = normalise_class_names(
        meta.get("class_names", ["Normal", "SVEB", "VEB"])
    )
    n_classes   = len(class_names)

    # ── Enum body ────────────────────────────────────────────────────────── #
    enum_lines = []
    for i, cn in enumerate(class_names):
        safe = cn.upper().replace(" ", "_").replace("-", "_")
        comma = "," if i < n_classes - 1 else ""
        enum_lines.append(f"        {safe} = {i}{comma}")
    enum_body = "\n".join(enum_lines)

    thresh_str = ", ".join(f"{t:.6f}f" for t in thresholds)

    # ── ECG normalisation section ─────────────────────────────────────────── #
    # The scaler may be global (fitted on the whole flattened signal → length 1)
    # or per-position (fitted feature-wise → length == beat_len).
    ecg_is_global = (len(ecg_mean) == 1)

    if ecg_is_global:
        ecg_norm_comment = (
            "// ECG normalisation - GLOBAL scalar (one mean/std for the whole window).\n"
            "    // Applied as: x_norm[i] = (x[i] - ECG_MEAN) / ECG_STD  for all i."
        )
        ecg_norm_consts = (
            f"{fmt_scalar(float(ecg_mean[0]), 'ECG_MEAN', 'global mean across all beat samples')}\n"
            f"{fmt_scalar(float(ecg_std[0]),  'ECG_STD',  'global std  across all beat samples')}"
        )
        ecg_mode_define = "    constexpr bool ECG_SCALER_GLOBAL = true;"
    else:
        ecg_norm_comment = (
            f"// ECG normalisation - PER-POSITION arrays (one mean/std per time step).\n"
            f"    // Applied as: x_norm[i] = (x[i] - ECG_MEAN[i]) / ECG_STD[i]."
        )
        ecg_norm_consts = (
            f"{fmt_array(ecg_mean, 'ECG_MEAN', f'[{beat_len}] per-position means')}\n"
            f"{fmt_array(ecg_std,  'ECG_STD',  f'[{beat_len}] per-position stds')}"
        )
        ecg_mode_define = "    constexpr bool ECG_SCALER_GLOBAL = false;"

    text = dedent(f"""\
    #pragma once
    /**
     * @file  model_config.h
     * @brief Normalisation constants and inference configuration.
     *
     * Auto-generated by extract_constants.py - DO NOT EDIT.
     *
     * ECG scaler mode : {"GLOBAL scalar (length 1)" if ecg_is_global else f"per-position arrays (length {beat_len})"}
     * RR  scaler mode : per-feature arrays (length {n_rr})
     *
     * Decision thresholds: a beat is classified only when its softmax score
     * meets the per-class threshold.  If no class qualifies, argmax is still
     * returned but InferenceResult::valid is set false.
     */
    #include <stdint.h>
    #include <stddef.h>

    namespace ModelCfg {{

        // -- Architecture ----------------------------------------------------
        constexpr size_t  BEAT_LENGTH   = {beat_len}U;
        constexpr size_t  N_RR_FEATURES = {n_rr}U;
        constexpr uint8_t NUM_CLASSES   = {n_classes}U;

        enum Classification : uint8_t {{
    {enum_body}
        }};

        // -- Per-class decision thresholds ------------------------------------
        constexpr float THRESHOLDS[{n_classes}] = {{{thresh_str}}};

        // -- ECG normalisation ------------------------------------------------
        {ecg_norm_comment}
    {ecg_norm_consts}
    {ecg_mode_define}

        // -- RR feature normalisation (per-feature StandardScaler) ------------
        // Features in order: pre_rr_norm, post_rr_norm, ratio_rr
    {fmt_array(rr_mean, "RR_MEAN", f"[{n_rr}] per-feature means")}
    {fmt_array(rr_std,  "RR_STD",  f"[{n_rr}] per-feature stds")}

        // -- Guard against zero std ------------------------------------------
        constexpr float STD_EPS = 1e-6f;

    }} // namespace ModelCfg
    """)
    out.write_text(text, encoding="utf-8")
    print(f"  model_config.h -> {out}")

def write_mobile_metadata(
    meta: dict,
    ecg_mean: np.ndarray,
    ecg_std: np.ndarray,
    rr_mean: np.ndarray,
    rr_std: np.ndarray,
    thresholds: list[float],
    out: Path,
) -> None:
    """Generate JSON metadata for Android app."""
    import json
    
    class_names = normalise_class_names(meta.get("class_names", ["Normal", "SVEB", "VEB"]))
    
    # Color mapping
    colors = {
        "Normal": "#4CAF50",           # Green
        "Supraventricular": "#FF9800", # Orange
        "SVEB": "#FF9800",             # Orange (alias)
        "Ventricular": "#F44336",      # Red
        "VEB": "#F44336"               # Red (alias)
    }
    
    metadata = {
        "version": "1.0.0",
        "beat_length": int(meta.get("beat_length", 250)),
        "n_rr_features": int(meta.get("n_rr_features", 3)),
        "sample_rate_hz": 250,
        "classes": [
            {
                "id": i,
                "name": name,
                "color": colors.get(name, "#9E9E9E")
            }
            for i, name in enumerate(class_names)
        ],
        "thresholds": [float(t) for t in thresholds],
        "ecg_scaler": {
            "mean": float(ecg_mean[0] if len(ecg_mean) == 1 else ecg_mean.mean()),
            "std": float(ecg_std[0] if len(ecg_std) == 1 else ecg_std.mean()),
            "per_position": len(ecg_mean) > 1
        },
        "rr_scaler": {
            "mean": rr_mean.tolist(),
            "std": rr_std.tolist()
        }
    }
    
    out.write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(f"  model_metadata.json -> {out}")

# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #

def main():
    parser = argparse.ArgumentParser(
        description="Generate model_data.h + model_config.h from TFLite + pickles"
    )
    parser.add_argument("--tflite",     required=True)
    parser.add_argument("--meta",       required=True)
    parser.add_argument("--ecg_scaler", required=True)
    parser.add_argument("--rr_scaler",  required=True)
    parser.add_argument("--results",    required=True,
                        help="results_XXXXXX.pkl containing thresholds")
    parser.add_argument("--out_data",   default="src/ml/model_data.h")
    parser.add_argument("--out_cfg",    default="src/ml/model_config.h")
    args = parser.parse_args()

    # ── Load ─────────────────────────────────────────────────────────────── #
    tflite_path = Path(args.tflite)
    if not tflite_path.exists():
        sys.exit(f"ERROR: TFLite file not found: {tflite_path}")

    meta       = load_pkl(args.meta)
    ecg_scaler = load_pkl(args.ecg_scaler)
    rr_scaler  = load_pkl(args.rr_scaler)
    results    = load_pkl(args.results)

    # ── Extract scaler arrays ─────────────────────────────────────────────── #
    ecg_mean = np.asarray(ecg_scaler.mean_,  dtype=np.float32).ravel()
    ecg_std  = np.asarray(ecg_scaler.scale_, dtype=np.float32).ravel()
    rr_mean  = np.asarray(rr_scaler.mean_,   dtype=np.float32).ravel()
    rr_std   = np.asarray(rr_scaler.scale_,  dtype=np.float32).ravel()

    # ── Extract thresholds ────────────────────────────────────────────────── #
    thresholds = None
    for key in ("thresholds", "optimal_thresholds", "class_thresholds",
                "decision_thresholds"):
        if key in results:
            thresholds = list(results[key])
            print(f"  Found thresholds under key '{key}': {thresholds}")
            break

    if thresholds is None:
        print("WARNING: Could not find thresholds in results pkl.")
        print("  Keys present:", list(results.keys()))
        print("  Using hardcoded defaults [0.234, 0.05, 0.05]")
        thresholds = [0.234, 0.05, 0.05]

    # ── Normalise metadata ────────────────────────────────────────────────── #
    beat_len    = int(meta.get("beat_length",   250))
    n_rr        = int(meta.get("n_rr_features", 3))
    class_names = normalise_class_names(
        meta.get("class_names", ["Normal", "SVEB", "VEB"])
    )

    ecg_is_global = (len(ecg_mean) == 1)

    # ── Sanity print ─────────────────────────────────────────────────────── #
    print("\n── Extracted constants summary ──────────────────────────────")
    print(f"  beat_length       : {beat_len}")
    print(f"  n_rr_features     : {n_rr}")
    print(f"  class_names       : {class_names}")
    print(f"  thresholds        : {thresholds}")
    print(f"  ecg scaler mode   : {'GLOBAL (length 1)' if ecg_is_global else f'per-position (length {len(ecg_mean)})'}")
    if ecg_is_global:
        print(f"  ECG_MEAN          : {ecg_mean[0]:.6f}")
        print(f"  ECG_STD           : {ecg_std[0]:.6f}")
    else:
        print(f"  ecg_mean range    : [{ecg_mean.min():.4f}, {ecg_mean.max():.4f}]")
        print(f"  ecg_std  range    : [{ecg_std.min():.4f}, {ecg_std.max():.4f}]")
    print(f"  rr_mean           : {rr_mean.tolist()}")
    print(f"  rr_std            : {rr_std.tolist()}")
    print("─────────────────────────────────────────────────────────────\n")

    # ── Validate ─────────────────────────────────────────────────────────── #
    if not ecg_is_global and len(ecg_mean) != beat_len:
        sys.exit(
            f"ERROR: ecg_scaler.mean_ has length {len(ecg_mean)} "
            f"but beat_length={beat_len}.\n"
            f"  Expected either length 1 (global scaler) or length {beat_len} "
            f"(per-position scaler)."
        )
    if len(rr_mean) != n_rr:
        sys.exit(
            f"ERROR: rr_scaler.mean_ has length {len(rr_mean)} "
            f"but n_rr_features={n_rr}"
        )
    if len(thresholds) != len(class_names):
        sys.exit(
            f"ERROR: {len(thresholds)} thresholds but {len(class_names)} classes"
        )

    # ── Write headers ─────────────────────────────────────────────────────── #
    Path(args.out_data).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out_cfg).parent.mkdir(parents=True, exist_ok=True)

    print("Generating model_data.h...")
    c_body, model_len = tflite_to_c_array(tflite_path)
    write_model_data_h(c_body, model_len, Path(args.out_data))

    print("Generating model_config.h...")
    write_model_config_h(
        meta, ecg_mean, ecg_std, rr_mean, rr_std, thresholds,
        Path(args.out_cfg)
    )

    print("Generating model_metadata.json for Android...")
    write_mobile_metadata(
        meta, ecg_mean, ecg_std, rr_mean, rr_std, thresholds,
        Path(args.out_cfg).parent / "model_metadata.json"
    )

    print("\nAll done ✓")
    print("  src/ml/model_data.h   — #include in Inference.cpp")
    print("  src/ml/model_config.h — #include in Inference.cpp")


if __name__ == "__main__":
    main()